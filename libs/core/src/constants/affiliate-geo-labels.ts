export type AffiliateGeoSelectOption = {
  value: ValidAffiliateGeo;
  label: string;
};

const CONTINENT_SET = new Set<string>(AFFILIATE_GEO_CONTINENT_ORDER);

export function affiliateGeoSelectOptions(): AffiliateGeoSelectOption[] {
  const continents = AFFILIATE_GEO_CONTINENT_ORDER.map((value) => ({
    value,
    label: AFFILIATE_GEO_LABELS[value],
  }));
  const countries = VALID_AFFILIATE_GEO.filter((code) => !CONTINENT_SET.has(code))
    .map((value) => ({ value, label: AFFILIATE_GEO_LABELS[value] }))
    .sort((a, b) => a.label.localeCompare(b.label, 'en'));
  return [...continents, ...countries];
}
